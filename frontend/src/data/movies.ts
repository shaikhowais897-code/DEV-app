export function generateRatingBreakdown(rating: number, count: number): MovieRatingBreakdown {
  const fiveRatio = Math.max(0.1, Math.min(0.85, (rating - 3.0) / 2.0 * 0.75 + 0.15));
  const fourRatio = Math.max(0.05, Math.min(0.4, (1 - fiveRatio) * 0.65));
  const threeRatio = Math.max(0.02, (1 - fiveRatio - fourRatio) * 0.65);
  const twoRatio = Math.max(0.01, (1 - fiveRatio - fourRatio - threeRatio) * 0.6);
  const oneRatio = Math.max(0.01, 1 - fiveRatio - fourRatio - threeRatio - twoRatio);

  const star5 = Math.round(count * fiveRatio);
  const star4 = Math.round(count * fourRatio);
  const star3 = Math.round(count * threeRatio);
  const star2 = Math.round(count * twoRatio);
  const star1 = Math.max(0, count - (star5 + star4 + star3 + star2));

  return {
    5: star5,
    4: star4,
    3: star3,
    2: star2,
    1: star1,
  };
}

export function enrichMovieWithRatings(movie: Movie): Movie {
  const seed = movie.id.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
  const defaultCount = 1200 + (seed % 3400);
  const ratingCount = movie.ratingCount || defaultCount;
  const communityRating = movie.communityRating ?? movie.rating;
  const ratingsBreakdown = movie.ratingsBreakdown || generateRatingBreakdown(communityRating, ratingCount);

  return {
    ...movie,
    communityRating,
    ratingCount,
    ratingsBreakdown,
  };
}

